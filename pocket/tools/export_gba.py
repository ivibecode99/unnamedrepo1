#!/usr/bin/env python3
"""Generates the Butano (GBA) graphics + level headers from the shared generators (same art and levels as GB/GBC)."""
import os, sys
sys.path.insert(0, os.path.dirname(__file__))
from PIL import Image
import art, levels
import export_gb as gb          # reuse palettes / tile classes

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
GFX = os.path.join(ROOT, "gba", "graphics")
INC = os.path.join(ROOT, "gba", "include")
os.makedirs(GFX, exist_ok=True); os.makedirs(INC, exist_ok=True)
for d in ("audio", "dmg_audio", "src"):
    os.makedirs(os.path.join(ROOT, "gba", d), exist_ok=True)

def save_indexed(path, w, h, pixels, palette):
    """pixels: list of rows of palette indices. palette: list of (r,g,b), padded to 256."""
    im = Image.new("P", (w, h))
    pal = []
    for c in palette[:256]:
        pal += list(c)
    pal += [0] * (768 - len(pal))
    im.putpalette(pal)
    im.putdata([p for row in pixels for p in row])
    im.save(path, format="BMP")

def write_json(name, body):
    import json
    with open(os.path.join(GFX, name + ".json"), "w") as f:
        json.dump(body, f, indent=4)

def gen_sprite(name, canvases, pal, frame_h):
    """canvases: list of art.Canvas frames (same size). Stacked vertically."""
    w = canvases[0].w
    h = canvases[0].h
    rows = []
    for cv in canvases:
        rows += cv.p
    palette = [(255, 0, 255)] + [tuple(c) for c in pal[1:]]
    save_indexed(os.path.join(GFX, name + ".bmp"), w, h * len(canvases), rows, palette + [(0, 0, 0)] * (16 - len(palette)))
    write_json(name, {"type": "sprite", "height": frame_h})

def pad(cv, w, h, ox, oy):
    out = art.Canvas(w, h)
    for y in range(cv.h):
        for x in range(cv.w):
            out.set(x + ox, y + oy, cv.p[y][x])
    return out

def gen_graphics():
    sp = gb.SPR_PAL
    gen_sprite("pip", [art.pip_frame(i) for i in range(4)], sp[0], 16)
    gen_sprite("piphat", [art.pip_hat_frame()], sp[3], 8)
    gen_sprite("hat", [art.hat_frame(0), art.hat_frame(1)], sp[3], 8)
    gen_sprite("walker", [art.walker_frame(0), art.walker_frame(1)], sp[1], 8)
    gen_sprite("flyer", [art.flyer_frame(0), art.flyer_frame(1)], sp[1], 8)
    gen_sprite("boss1", [pad(art.boss_beetle(), 32, 32, 4, 8)], sp[2], 32)
    gen_sprite("boss2", [pad(art.boss_baron(), 32, 32, 4, 8)], sp[4], 32)
    gen_sprite("proj", [art.projectile_frame(0), art.projectile_frame(1)], sp[3], 8)
    # BG tileset: one strip of 8x8 tiles (index == game tile id)
    tiles = art.bg_tiles()
    w = 8 * len(tiles)
    rows = [[0] * w for _ in range(8)]
    for i, t in enumerate(tiles):
        for y in range(8):
            for x in range(8):
                rows[y][i * 8 + x] = t[y][x]
    save_indexed(os.path.join(GFX, "bg_tiles.bmp"), w, 8, rows, [(0, 0, 0), (90, 90, 90), (170, 170, 170), (255, 255, 255)] + [(0, 0, 0)] * 12)
    write_json("bg_tiles", {"type": "regular_bg_tiles", "bpp_mode": "bpp_4"})
    # BG palette: 5 banks x 16 colours (forest theme default; overridden per level at runtime)
    pals = gb.bg_pal_for("forest") + [[(0, 0, 0), (255, 255, 255), (255, 255, 255), (255, 255, 255)]]   # bank 5 = HUD (white)
    colors = []
    for p in pals:
        colors += [tuple(c) for c in p] + [(0, 0, 0)] * 12
    save_indexed(os.path.join(GFX, "bg_pal.bmp"), 8, 8, [[0] * 8 for _ in range(8)], colors)
    write_json("bg_pal", {"type": "bg_palette", "bpp_mode": "bpp_4", "colors_count": 16 * len(pals)})

def c5(c):
    return "bn::color(%d, %d, %d)" % (c[0] >> 3, c[1] >> 3, c[2] >> 3)

def gen_header():
    lvls = levels.all_levels()
    th_idx = {"forest": 0, "desert": 1, "city": 2, "castle": 3}
    o = ["// GENERATED by pocket/tools/export_gba.py - do not edit.", "#ifndef GBA_DATA_H", "#define GBA_DATA_H", "#include \"bn_color.h\"", "#include <stdint.h>", ""]
    o.append("namespace data {")
    o.append("constexpr int level_h = %d;" % levels.H)
    o.append("constexpr int num_levels = %d;" % len(lvls))
    o.append("constexpr int num_bg_tiles = %d;" % art.NUM_BG_TILES)
    o.append("constexpr int font_base = %d;" % art.FONT_BASE)
    o.append("constexpr const char* font_chars = \"%s\";" % art.FONT_CHARS.replace("\\", "\\\\").replace('"', '\\"'))
    for n, i in art.BG_INDEX.items():
        o.append("constexpr int T_%s = %d;" % (n.upper(), i))
    cls = []
    for i in range(art.NUM_BG_TILES):
        v = 0
        if i < len(art.BG_ORDER):
            n = art.BG_ORDER[i]
            if n in gb.SOLID: v |= 1
            if n in gb.HAZARD: v |= 2
            if n == "coin": v |= 4
            if n == "star": v |= 8
        cls.append(v)
    o.append("constexpr uint8_t tile_class[%d] = { %s };" % (len(cls), ", ".join(map(str, cls))))
    o.append("constexpr uint8_t tile_palette[%d] = { %s };" % (art.NUM_BG_TILES, ", ".join(str(gb.tile_pal(i)) for i in range(art.NUM_BG_TILES))))
    # theme palettes: sky colour + 5 banks x 4 colours
    o.append("struct theme_pal { bn::color bank[5][4]; };")
    o.append("constexpr theme_pal theme_pals[4] = {")
    for th in ["forest", "desert", "city", "castle"]:
        banks = gb.bg_pal_for(th)
        o.append("  { { " + ", ".join("{ " + ", ".join(c5(c) for c in b) + " }" for b in banks) + " } },")
    o.append("};")
    o.append("struct enemy_spawn { int type, x, y; };")
    o.append("struct level_info { const char* name; int w, theme, boss, music, n_enemies, arena0, arena1, goal_x, goal_y; const uint8_t* tiles; const enemy_spawn* enemies; };")
    for i, lv in enumerate(lvls):
        cols = []
        for x in range(lv.w):
            for y in range(levels.H):
                cols.append(art.BG_INDEX[lv.g[x][y]])
        o.append("constexpr uint8_t lvl%d_tiles[%d] = {" % (i, len(cols)))
        for k in range(0, len(cols), 36):
            o.append("  " + ", ".join(map(str, cols[k:k + 36])) + ",")
        o.append("};")
        en = ", ".join("{%d,%d,%d}" % e for e in lv.enemies) or "{0,0,0}"
        o.append("constexpr enemy_spawn lvl%d_en[] = { %s };" % (i, en))
    o.append("constexpr level_info levels[num_levels] = {")
    for i, lv in enumerate(lvls):
        s = lv.spec
        o.append('  { "%s", %d, %d, %d, %d, %d, %d, %d, %d, %d, lvl%d_tiles, lvl%d_en },' % (
            s["name"], lv.w, th_idx[s["theme"]], s["boss"], s["music"], len(lv.enemies), lv.arena[0], lv.arena[1], lv.goal[0], lv.goal[1], i, i))
    o.append("};")
    o.append("}  // namespace data")
    o.append("#endif")
    open(os.path.join(INC, "gba_data.h"), "w").write("\n".join(o) + "\n")

if __name__ == "__main__":
    gen_graphics()
    gen_header()
    print("GBA assets generated")
