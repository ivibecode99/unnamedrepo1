def build_strings(ch):
    b = bytearray([len(UI_STRINGS)])
    for _, s in UI_STRINGS: b += s.encode() + b'\0'
    ch.fixed(CHK.LAYOUT['CH_STRINGS'], b, 'strings')
    with open(os.path.join(ROOT, 'core', 'gen_strings.h'), 'w') as f:
        f.write('/* generated by tools/build_data.py */\n')
        for i, (n, _) in enumerate(UI_STRINGS): f.write(f'#define {n} {i}\n')

def main():
    sys.path.insert(0, os.path.join(ROOT, 'content'))
    out = os.path.join(ROOT, 'build', 'gen')
    if '--out' in sys.argv: out = os.path.abspath(sys.argv[sys.argv.index('--out') + 1])
    os.makedirs(out, exist_ok=True)
    global GEN_OUT; GEN_OUT = out
